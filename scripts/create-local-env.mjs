import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const placeholderValues = new Set([
  'replace-with-a-strong-password',
  'replace-with-a-long-random-string',
]);

function parseEnvironment(contents) {
  const values = new Map();
  for (const [, key, value] of contents.matchAll(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/gm)) {
    if (!values.has(key)) values.set(key, value);
  }
  return values;
}

function encodeUserInfo(value) {
  return encodeURIComponent(value).replace(/[!'()*]/g, (character) => `%${character.charCodeAt(0).toString(16).toUpperCase()}`);
}

export function configureLocalEnvironment({
  directory = process.cwd(),
  requestedPort = process.env.LOCAL_POSTGRES_PORT,
} = {}) {
  const envPath = resolve(directory, '.env');
  const environmentExists = existsSync(envPath);
  const existingContents = environmentExists ? readFileSync(envPath, 'utf8') : '';
  const existingValues = parseEnvironment(existingContents);
  const localPostgresPort = existingValues.get('LOCAL_POSTGRES_PORT') || requestedPort || '5432';

  if (!/^[1-9]\d{0,4}$/.test(localPostgresPort) || Number(localPostgresPort) > 65535) {
    throw new Error('LOCAL_POSTGRES_PORT must be a number from 1 to 65535.');
  }

  const valueFor = (key, fallback) => {
    const value = existingValues.get(key);
    return value && !placeholderValues.has(value) ? value : fallback;
  };
  const postgresUser = valueFor('POSTGRES_USER', 'postgres');
  // Hex credentials are URL-safe, so generated values can be used in the URL
  // without additional escaping.
  const postgresPassword = valueFor('POSTGRES_PASSWORD', randomBytes(32).toString('hex'));
  const postgresDatabase = valueFor('POSTGRES_DB', 'priceghost');
  const jwtSecret = valueFor('JWT_SECRET', randomBytes(48).toString('hex'));
  const databaseUrl = `postgresql://${encodeUserInfo(postgresUser)}:${encodeUserInfo(postgresPassword)}@127.0.0.1:${localPostgresPort}/${encodeURIComponent(postgresDatabase)}`;

  const valuesToConfigure = new Map([
    ['POSTGRES_USER', postgresUser],
    ['POSTGRES_PASSWORD', postgresPassword],
    ['POSTGRES_DB', postgresDatabase],
    ['JWT_SECRET', jwtSecret],
    ['DATABASE_URL', databaseUrl],
    ['LOCAL_POSTGRES_PORT', localPostgresPort],
  ]);
  const entriesToReplace = [...valuesToConfigure].filter(([key]) => existingValues.has(key) && !valueFor(key, ''));
  const missingEntries = [...valuesToConfigure].filter(([key]) => !existingValues.has(key));

  if (entriesToReplace.length === 0 && missingEntries.length === 0) {
    return { changedKeys: [], envPath };
  }

  let contents = existingContents;
  for (const [key, value] of entriesToReplace) {
    contents = contents.replace(new RegExp(`^${key}=.*$`, 'gm'), `${key}=${value}`);
  }
  if (missingEntries.length > 0) {
    const prefix = contents.length > 0 && !contents.endsWith('\n') ? '\n' : '';
    const heading = contents.length === 0
      ? '# Generated by `make dev-env` for local development. Do not commit this file.\n'
      : '# Added by `make dev-env` for local development.\n';
    const additions = missingEntries.map(([key, value]) => `${key}=${value}`).join('\n');
    contents += `${prefix}${heading}${additions}\n`;
  }
  writeFileSync(envPath, contents, {
    encoding: 'utf8',
    mode: 0o600,
    flag: environmentExists ? 'w' : 'wx',
  });

  return {
    changedKeys: [...entriesToReplace, ...missingEntries].map(([key]) => key),
    envPath,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { changedKeys } = configureLocalEnvironment();
    if (changedKeys.length === 0) {
      console.log('.env already contains local development settings; it was not changed.');
    } else {
      console.log(`Configured ${changedKeys.join(', ')} in .env. Run \`make dev\` to start PostgreSQL and hot reload.`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
